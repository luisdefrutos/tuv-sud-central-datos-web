-- Informe C3: Facturación de Inspecciones Comparativa (TSA / CAL)
-- Agrupa por Rango (1 = Primer Rango/Año, 2 = Segundo Rango/Año) y Estación
SELECT 
    1 AS RangoId,
    LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') AS CodEstacion,
    CASE 
        WHEN b.DESESTACION LIKE '%BORGES BLANQUES%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'BORGES BLANQUES', 'LES BORGES')
        WHEN b.DESESTACION LIKE '%MIRANDA DE EBRO%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'MIRANDA DE EBRO', 'MIRANDA')
        WHEN b.DESESTACION LIKE '%VILLALBA%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'VILLALBA', 'C. VILLALBA')
        WHEN b.DESESTACION LIKE '%VILLASANTE DE MONTIJA%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'VILLASANTE DE MONTIJA', 'VILLASANTE')
        WHEN b.DESESTACION LIKE '%CUELLAR%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'CUELLAR', 'CUÉLLAR')
        ELSE LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1))
    END AS DesEstacion,
    CASE 
        WHEN LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') IN ('0902', '0903', '0906', '0908') OR LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') LIKE '09%' THEN 'CAL'
        ELSE 'TSA'
    END AS ClaveSociedad,
    COUNT(CASE WHEN i.ANULADA = 0 AND i.INDICA12 = 1 THEN 1 END) AS TotalInspecciones,
    NVL(SUM(i.TARIFA + i.TARIFADIESEL + i.TASAAUX1 - NVL(i.DESCUENTO, 0)), 0) AS TotalIngresos
FROM CENTRALITV.INSPECCION i
JOIN CENTRALITV.INSTANCIAS_BBDD b ON i.CODESTACION = b.CODESTACION
WHERE i.FECHAINSPECCION >= :FechaInicioRango1 AND i.FECHAINSPECCION <= :FechaFinRango1
  AND i.ANULADA = 0
  AND b.TIPO_ESTACION = 'ITV' AND b.ACTIVO = -1
  /*FILTRO_ESTACIONES_R1*/
GROUP BY i.CODESTACION, b.DESESTACION

UNION ALL

SELECT 
    2 AS RangoId,
    LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') AS CodEstacion,
    CASE 
        WHEN b.DESESTACION LIKE '%BORGES BLANQUES%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'BORGES BLANQUES', 'LES BORGES')
        WHEN b.DESESTACION LIKE '%MIRANDA DE EBRO%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'MIRANDA DE EBRO', 'MIRANDA')
        WHEN b.DESESTACION LIKE '%VILLALBA%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'VILLALBA', 'C. VILLALBA')
        WHEN b.DESESTACION LIKE '%VILLASANTE DE MONTIJA%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'VILLASANTE DE MONTIJA', 'VILLASANTE')
        WHEN b.DESESTACION LIKE '%CUELLAR%' THEN REPLACE(LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1)), 'CUELLAR', 'CUÉLLAR')
        ELSE LTRIM(SUBSTR(b.DESESTACION, INSTR(b.DESESTACION, '- ') + 1))
    END AS DesEstacion,
    CASE 
        WHEN LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') IN ('0902', '0903', '0906', '0908') OR LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') LIKE '09%' THEN 'CAL'
        ELSE 'TSA'
    END AS ClaveSociedad,
    COUNT(CASE WHEN i.ANULADA = 0 AND i.INDICA12 = 1 THEN 1 END) AS TotalInspecciones,
    NVL(SUM(i.TARIFA + i.TARIFADIESEL + i.TASAAUX1 - NVL(i.DESCUENTO, 0)), 0) AS TotalIngresos
FROM CENTRALITV.INSPECCION i
JOIN CENTRALITV.INSTANCIAS_BBDD b ON i.CODESTACION = b.CODESTACION
WHERE i.FECHAINSPECCION >= :FechaInicioRango2 AND i.FECHAINSPECCION <= :FechaFinRango2
  AND i.ANULADA = 0
  AND b.TIPO_ESTACION = 'ITV' AND b.ACTIVO = -1
  /*FILTRO_ESTACIONES_R2*/
GROUP BY i.CODESTACION, b.DESESTACION
