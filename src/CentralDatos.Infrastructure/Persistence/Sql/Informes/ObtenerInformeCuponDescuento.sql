SELECT /*+ INDEX(i P17_INSPECCION P31_INSPECCION) */
    i.CODINSPECCION,
    LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0') AS CODESTACION,
    NVL(e.DesEstacion, 'Estación ' || LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0')) AS DESESTACION,
    NVL(e.Cod_Empresa, '01') AS COD_EMPRESA,
    CASE WHEN e.Cod_Empresa = '03' THEN 'CAL ITV S.L.U.' ELSE 'TÜV SÜD ATISAE S.A.U.' END AS NOMBRE_EMPRESA,
    CASE WHEN e.Cod_Empresa = '03' THEN 'CAL' ELSE 'TSA' END AS CLAVE_SOCIEDAD,
    TRIM(i.MATRICULA) AS MATRICULA,
    i.FECHAINSPECCION,
    TRIM(i.CODCUPON) AS CODCUPON,
    NVL(TRIM(c.PROMOCION), 'Sin descripción') AS PROMOCION,
    NVL(i.DESCUENTO, 0) AS DESCUENTO,
    ROUND(
        NVL(i.TARIFA, 0) + NVL(i.TASAAUX1, 0) + NVL(i.TARIFADIESEL, 0) + NVL(i.IVATARIFA, 0) + NVL(i.TASATRAFICO, 0) + NVL(i.TASAINDUSTRIA, 0) - NVL(i.DESCUENTO, 0),
        2
    ) AS IMPORTE_ABONADO,
    NVL(TRIM(i.MARCA), 'S/D') AS MARCA,
    NVL(TRIM(i.MODELO), 'S/D') AS MODELO,
    NVL(TRIM(i.TIPOMOTOR), 'S/D') AS TIPO_MOTOR,
    NVL(TRIM(i.TIPOVEHICULO), 'S/D') AS TIPO_VEHICULO,
    NVL(TRIM(i.CODSEPIVA), '001') AS TIPO_INSPECCION,
    CASE 
        WHEN i.RESULTADO = '1' THEN 'Favorable'
        WHEN i.RESULTADO = '2' THEN 'Favorable con Defectos Leves'
        WHEN i.RESULTADO = '3' THEN 'Desfavorable'
        WHEN i.RESULTADO = '4' THEN 'Negativa'
        ELSE NVL(TRIM(i.RESULTADO), 'Desconocido')
    END AS TEXTO_RESULTADO,
    i.RESULTADO,
    CASE 
        WHEN i.INDICA12 = '2' THEN '2ª Fase'
        ELSE '1ª Fase'
    END AS FASE,
    i.INDICA12,
    NVL(TRIM(i.CHOMOLOGACION), '') AS CHOMOLOGACION,
    NVL(TRIM(i.CODCONSTRUCCION || i.CODUTILIZACION), '') AS CLASIFICACION,
    i.MMA,
    NVL(TO_CHAR(i.KILOMETRAJE), '') AS KILOMETRAJE
FROM CENTRALITV.INSPECCION i
LEFT JOIN CENTRALITV.CUPONES c ON i.CODCUPON = c.CODCUPON
LEFT JOIN CENTRALITV.ESTACIONES e ON LPAD(TRIM(TO_CHAR(e.CodEstacion)), 4, '0') = LPAD(TRIM(TO_CHAR(i.CODESTACION)), 4, '0')
WHERE i.ANULADA = 0
  AND i.CODCUPON IS NOT NULL
  AND i.FECHAINSPECCION >= :p_fecha_inicio
  AND i.FECHAINSPECCION <= :p_fecha_fin
/*WHERE_EXTRA*/
ORDER BY i.FECHAINSPECCION ASC
